import numpy as np
arr1 = np.array([10, 20, 30, 40, 50, 60])
arr2 = np.array([1, 2, 3, 4, 5, 6])
print("Array 1:", arr1)
print("Array 2:", arr2)

print("\nElement-wise Operations using ufuncs:")
print("Addition (np.add):", np.add(arr1, arr2))
print("Subtraction (np.subtract):", np.subtract(arr1, arr2))
print("Multiplication (np.multiply):", np.multiply(arr1, arr2))
print("Division (np.divide):", np.divide(arr1, arr2))
print("Square Root (np.sqrt) of arr1:", np.sqrt(arr1))
print("Exponential (np.exp) of arr1:", np.exp(arr1))
